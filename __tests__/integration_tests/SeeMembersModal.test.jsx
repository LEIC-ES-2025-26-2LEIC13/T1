import React from 'react';
import { render, screen, fireEvent, waitFor } from '@testing-library/react-native';
import SeeMembersModal from '../../components/SeeMembersModal';
import { useAuth } from '../../hooks/useAuth';

// Mock firebase because of unexpected token issues with jest
jest.mock('firebase/auth', () => ({}));
jest.mock('../../firebase/firebaseConfig', () => ({}));

// Mock the useAuth hook
jest.mock('../../hooks/useAuth');

// Mock OverflowMenu so we can trigger the actions without dealing with react-native-popup-menu and Alert
jest.mock('../../components/OverflowMenu', () => {
    const { View, Pressable, Text } = require('react-native');
    return function MockOverflowMenu({ actions }) {
        return (
            <View testID="mock-overflow-menu">
                {actions.map(action => (
                    <Pressable 
                        key={action.id} 
                        testID={`action-${action.id}`} // generates different testIDs
                        onPress={action.onPress}
                    >
                    </Pressable>
                ))}
            </View>
        );
    };
});

describe('SeeMembersModal Integration Tests', () => {

    //  To handle react state updates issue when running the tests
    beforeAll(() => {
        jest.useFakeTimers();
    });

    afterAll(() => {
        jest.useRealTimers();
    });

    // Fake current user
    const mockCurrentUser = { email: 'me@example.com' };
    
    // Fake project returned by the prop
    let mockProjectUsers = [
        { id: '1', email: 'alice@example.com' },
        { id: '2', email: 'me@example.com' }, // Current user
        { id: '3', email: 'bob@example.com' }
    ];

    let mockGetProjectUsers;
    let mockOnClose;
    let mockOnKickMember;

    beforeEach(() => {
        // Reset all mocks before each test
        jest.clearAllMocks();

        useAuth.mockReturnValue({ user: mockCurrentUser });
        mockGetProjectUsers = jest.fn().mockImplementation(() => Promise.resolve(mockProjectUsers));
        mockOnClose = jest.fn();
        mockOnKickMember = jest.fn().mockResolvedValue();
    });

    it('renders correctly and fetches members when visible is true', async () => {
        render(
            <SeeMembersModal 
                visible={true} 
                getProjectUsers={mockGetProjectUsers} 
                onClose={mockOnClose} 
                onKickMember={mockOnKickMember}
            />
        );

        // Verify the function was called
        expect(mockGetProjectUsers).toHaveBeenCalledTimes(1);

        // Wait for the async useEffect to finish and populate the FlatList
        // findByText automatically waits for the element to appear
        const currentUserElement = await screen.findByText('Me (me@example.com)');
        expect(currentUserElement).toBeTruthy();

        // Check if other users are rendered properly
        expect(screen.getByText('alice@example.com')).toBeTruthy();
        expect(screen.getByText('bob@example.com')).toBeTruthy();
    });

    it('handles the onClose button press', async () => {
        render(
            <SeeMembersModal 
                visible={true} 
                getProjectUsers={mockGetProjectUsers} 
                onClose={mockOnClose} 
                onKickMember={mockOnKickMember}
            />
        );

        await screen.findByText('Me (me@example.com)');

        const closeBtn = screen.getByTestId('see-members-close');
        fireEvent.press(closeBtn);

        expect(mockOnClose).toHaveBeenCalledTimes(1);
    });

    it('handles kicking another member and updating the list immediately', async () => {
        render(
            <SeeMembersModal 
                visible={true} 
                getProjectUsers={mockGetProjectUsers} 
                onClose={mockOnClose} 
                onKickMember={mockOnKickMember}
            />
        );

        await screen.findByText('Me (me@example.com)');

        // Clear the initial fetch call, to track calls made after kicking a member
        mockGetProjectUsers.mockClear();

        // Change mock implementation to simulate a user being removed
        mockGetProjectUsers.mockImplementation(() => Promise.resolve([
            { id: '2', email: 'me@example.com' },
            { id: '3', email: 'bob@example.com' }
        ]));

        // Press 'Kick member' for alice directly (which is the first action on the screen)
        // Since Alice is not the current user, it renders 'Kick member'
        const kickAction = screen.getAllByTestId('action-kick-member')[0]; // testId generated by the mocked OverflowMenu
        
        await waitFor(async () => {
            fireEvent.press(kickAction); // kick Alice
        })

        // Checking if onKickMember was called with Alice's details
        expect(mockOnKickMember).toHaveBeenCalledWith('1', 'alice@example.com');
        
        // Since it's another user, updateMembers should be called (which calls getProjectUsers again)
        expect(mockGetProjectUsers).toHaveBeenCalledTimes(1);
    });

    it('handles leaving the project and does not update list immediately', async () => {
        render(
            <SeeMembersModal 
                visible={true} 
                getProjectUsers={mockGetProjectUsers} 
                onClose={mockOnClose} 
                onKickMember={mockOnKickMember}
            />
        );

        await screen.findByText('Me (me@example.com)');
        mockGetProjectUsers.mockClear(); // Clear the initial fetch call, to track calls made after leaving the project

        // Target 'leave-project' action
        const leaveAction = screen.getByTestId('action-leave-project');

        await waitFor(async () => {
            fireEvent.press(leaveAction);
        })

        expect(mockOnKickMember).toHaveBeenCalledWith('2', 'me@example.com');
        
        // Since user is leaving, updateMembers shouldn't be called to fetch project users again
        expect(mockGetProjectUsers).not.toHaveBeenCalled();
    });
})
